'use strict';

/**
 * Summarise every captured fixture against the current library build, as Markdown.
 *
 *   node report.js > ../../docs/client-coverage.md
 *
 * Besides per client pass rates, it lists the boundary lines the library failed to act on: for
 * each failing reply, the line just above the first quoted token, and for each failing forward,
 * the line above the first forwarded token. Those are the attribution and forward header formats
 * the pattern files do not know yet, which is the actionable output of the whole exercise.
 */

const fs = require('node:fs');
const { score } = require('./lib/score');
const { walkFixtures } = require('./lib/fixtures');
const { findTokens } = require('./lib/scenario');

/** The non empty line above the first token of a role, in the canonical text the library saw. */
function boundaryLine(text, role) {
    const lines = text.split('\n');
    const index = lines.findIndex(line => findTokens(line).some(found => found.role === role));
    for (let i = index - 1; i >= 0; i--) {
        const line = lines[i].replace(/^[>\s]+/, '').trim();
        if (line && !/^-+\s*$/.test(line) && !findTokens(line).length) {
            return line.length > 140 ? `${line.slice(0, 140)}...` : line;
        }
    }
    return null;
}

function outcomeOf(result) {
    const bad = result.tokens.filter(item => item.outcome !== 'ok');
    if (!bad.length) {
        return 'ok';
    }
    // Most severe first.
    for (const kind of ['content-hidden', 'mislabel', 'history-visible', 'missing']) {
        const hit = bad.find(item => item.outcome === kind);
        if (hit) {
            return `${kind}: ${hit.expected.join('|')} as ${hit.actual}`;
        }
    }
    return 'other';
}

async function main() {
    const clients = new Map();
    const boundaries = [];
    for (const { file, meta } of walkFixtures()) {
        const raw = fs.readFileSync(file);
        const result = await score(raw, meta.expected);
        const outcome = outcomeOf(result);
        const stats = clients.get(meta.client) || { total: 0, ok: 0, locales: new Set(), outcomes: new Map() };
        stats.total++;
        stats.ok += outcome === 'ok' ? 1 : 0;
        stats.locales.add(meta.locale);
        if (outcome !== 'ok') {
            const key = `${meta.scenario} ${meta.compose}: ${outcome}`;
            stats.outcomes.set(key, (stats.outcomes.get(key) || 0) + 1);
            const role = meta.scenario === 'forward' ? 'F' : 'H1';
            // Canonical text per MIME part; use whichever part holds the role's tokens.
            const texts = Object.values(result.canonicalText).filter(text => findTokens(text).some(found => found.role === role));
            const line = texts.map(text => boundaryLine(text, role)).find(Boolean) || null;
            if (line) {
                boundaries.push({ client: meta.client, locale: meta.locale, scenario: meta.scenario, compose: meta.compose, outcome, line });
            }
        }
        clients.set(meta.client, stats);
    }

    const out = [];
    out.push('# Client coverage');
    out.push('');
    out.push('Generated by `tools/client-capture/report.js` from the fixtures in `test/fixtures/clients/`, scored');
    out.push('against the library build it ran on. Each fixture is a real reply or forward produced by the named');
    out.push('client, labelled automatically by sentinel tokens (see `tools/client-capture/README.md`).');
    out.push('');
    out.push('| client | fixtures | fully correct | locales |');
    out.push('| --- | ---: | ---: | ---: |');
    let total = 0;
    let ok = 0;
    for (const [client, stats] of [...clients].sort()) {
        total += stats.total;
        ok += stats.ok;
        out.push(`| ${client} | ${stats.total} | ${stats.ok} | ${stats.locales.size} |`);
    }
    out.push(`| **all** | **${total}** | **${ok}** | |`);
    out.push('');
    out.push('## Failure modes by client');
    out.push('');
    out.push('Outcomes name the first, most severe wrong token: `content-hidden` is text that should be visible');
    out.push('coming back hidden, `mislabel` is a wrong visible label, `history-visible` is history left shown.');
    for (const [client, stats] of [...clients].sort()) {
        if (!stats.outcomes.size) {
            continue;
        }
        out.push('');
        out.push(`### ${client}`);
        out.push('');
        out.push('| scenario and outcome | fixtures |');
        out.push('| --- | ---: |');
        for (const [key, count] of [...stats.outcomes].sort((a, b) => b[1] - a[1])) {
            out.push(`| ${key} | ${count} |`);
        }
    }
    out.push('');
    out.push('## Boundary lines the library did not act on');
    out.push('');
    out.push('The line directly above the first quoted or forwarded token in each failing fixture. These are');
    out.push('the attribution lines and forward headers to consider for `src/detect/patterns/*.json`.');
    out.push('');
    out.push('| client | locale | scenario | line |');
    out.push('| --- | --- | --- | --- |');
    const seen = new Set();
    for (const item of boundaries.sort((a, b) => `${a.client}${a.locale}`.localeCompare(`${b.client}${b.locale}`))) {
        const key = `${item.client}|${item.scenario}|${item.line}`;
        if (seen.has(key)) {
            continue;
        }
        seen.add(key);
        out.push(`| ${item.client} | ${item.locale} | ${item.scenario} ${item.compose} | \`${item.line.replace(/\|/g, '\\|').replace(/`/g, "'")}\` |`);
    }
    process.stdout.write(`${out.join('\n')}\n`);
}

main().catch(err => {
    console.error(err);
    process.exit(1);
});
